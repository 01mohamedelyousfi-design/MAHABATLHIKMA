/**
 * build-lesson-catalog.js
 *
 * Derives the machine-readable MahabatLhikma lesson catalog from the single
 * source of truth: the LESSONS_DATA object embedded in lessons/index.html.
 *
 * Outputs:
 *   assets/data/lessons.catalog.json  (public, consumed by the website)
 *   worker/src/catalog-data.js        (ESM module bundled with the Worker)
 *
 * Stable lesson IDs are defined ONCE here (LESSON_ID_MAP). They must never
 * change, even if a lesson URL changes, because review programs in the
 * database reference them. A lesson found in LESSONS_DATA without a mapped
 * stable ID fails the build on purpose.
 */
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = path.join(__dirname, '..');
const INDEX_HTML = path.join(ROOT, 'lessons', 'index.html');
const OUT_JSON = path.join(ROOT, 'assets', 'data', 'lessons.catalog.json');
const OUT_WORKER = path.join(ROOT, 'worker', 'src', 'catalog-data.js');

/** slug of the intro page -> stable identity of the lesson */
const LESSON_ID_MAP = {
  'lesson-identity': {
    id: 'person-identity',
    title: 'هوية الشخص',
    pages: {
      intro: '/lessons/lesson-identity',
      philosophers: '/lessons/philosophers',
      synthesis: '/lessons/lesson-identity-synthesis',
    },
  },
  'lesson-value': {
    id: 'person-value',
    title: 'قيمة الشخص',
    pages: {
      intro: '/lessons/lesson-value',
      philosophers: '/lessons/philosophers-value',
      synthesis: '/lessons/lesson-value-synthesis',
    },
  },
  'lesson-freedom': {
    id: 'necessity-freedom',
    title: 'الشخص بين الضرورة والحرية',
    pages: {
      intro: '/lessons/lesson-freedom',
      philosophers: '/lessons/philosophers-freedom',
      synthesis: '/lessons/lesson-freedom-synthesis',
    },
  },
};

function extractLessonsData(html) {
  const marker = 'const LESSONS_DATA =';
  const start = html.indexOf(marker);
  if (start === -1) throw new Error('LESSONS_DATA not found in lessons/index.html');
  // Find the end of the object literal: first "};" at the same nesting level.
  let i = html.indexOf('{', start);
  let depth = 0;
  let end = -1;
  for (; i < html.length; i++) {
    const ch = html[i];
    if (ch === '{') depth++;
    else if (ch === '}') {
      depth--;
      if (depth === 0) { end = i + 1; break; }
    }
  }
  if (end === -1) throw new Error('Could not parse LESSONS_DATA literal');
  const literal = html.slice(html.indexOf('{', start), end);
  return vm.runInNewContext('(' + literal + ')', Object.create(null));
}

function buildCatalog(data) {
  const catalog = [];
  for (const level of data.levels || []) {
    for (const module of level.modules || []) {
      for (const concept of module.concepts || []) {
        for (const lesson of concept.lessons || []) {
          if (lesson.external) continue; // external activities are not reviewable lessons
          const slug = String(lesson.url).split('/').filter(Boolean).pop();
          const mapped = LESSON_ID_MAP[slug];
          if (!mapped) {
            throw new Error(
              `Lesson "${lesson.title}" (${lesson.url}) has no stable ID in LESSON_ID_MAP. ` +
              'Add one in scripts/build-lesson-catalog.js before publishing it to the memory program.'
            );
          }
          catalog.push({
            id: mapped.id,
            title: mapped.title,
            url: mapped.pages.intro,
            pages: mapped.pages,
            level: level.id,
            levelName: level.name,
            moduleId: module.id,
            module: module.name,
            concept: concept.name,
          });
        }
      }
    }
  }
  return catalog;
}

function main() {
  const html = fs.readFileSync(INDEX_HTML, 'utf8');
  const data = extractLessonsData(html);
  const catalog = buildCatalog(data);

  fs.mkdirSync(path.dirname(OUT_JSON), { recursive: true });
  fs.writeFileSync(OUT_JSON, JSON.stringify(catalog, null, 2) + '\n', 'utf8');

  fs.mkdirSync(path.dirname(OUT_WORKER), { recursive: true });
  fs.writeFileSync(
    OUT_WORKER,
    '// AUTO-GENERATED by scripts/build-lesson-catalog.js — do not edit by hand.\n' +
    '// Source of truth: LESSONS_DATA in lessons/index.html.\n' +
    'export const LESSON_CATALOG = ' + JSON.stringify(catalog, null, 2) + ';\n',
    'utf8'
  );

  console.log(`catalog: ${catalog.length} lessons -> ${path.relative(ROOT, OUT_JSON)} + worker/src/catalog-data.js`);
  for (const l of catalog) console.log(`  - ${l.id}: ${l.title} (${l.url})`);
}

main();
